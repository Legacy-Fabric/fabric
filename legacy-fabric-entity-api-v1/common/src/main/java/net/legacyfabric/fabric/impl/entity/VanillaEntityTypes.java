	public static void init(Map<Integer, Class<? extends Entity>> values, Registry<Class<? extends Entity>> registry) {
		for (Map.Entry<Integer, Class<? extends Entity>> entry : values.entrySet()) {
			register(entry.getKey(), entry.getValue(), registry);
		}
	}

	static void register(int id, Class<? extends Entity> type, Registry<Class<? extends Entity>> registry) {
		if (id >= 0 && id < IDENTIFIERS.length) {
			String identifier = IDENTIFIERS[id];

			if (identifier != null) {
				Registry.register(registry, id, NamespacedIdentifiers.from(identifier), type);
			}
		}
	}
